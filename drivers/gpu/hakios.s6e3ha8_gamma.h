/* what is worked out from the MTP, once */
struct ha8_work {
	int32_t offset[HA8_TP][3];      /* the MTP, per point and colour (VT's are 0-15) */
	int64_t point[HA8_TP][3];       /* the calibrated curve's voltage at each point */
	int64_t gray[256][3];           /* and at every gray (gray 0: VREGOUT) */
	uint32_t clamped;               /* values step 3 kept within range */
};

/* C8's 34 bytes as offsets (s6e3ha8.c: mtp_ctoi) */
static void
ha8_mtp(const uint8_t mtp[HA8_CA], int32_t offset[HA8_TP][3])
{
	unsigned at = 1;

	for (int p = HA8_V255; p > HA8_VT; p--) {
		for (int c = 0; c < 3; c++, at++) {
			bool negative = p == HA8_V255 ? (mtp[0] & 1) : (mtp[at] & 0x80);
			int32_t size = p == HA8_V255 ? mtp[at] : (mtp[at] & 0x7F);

			offset[p][c] = negative ? -size : size;
		}
	}
	offset[HA8_VT][0] = mtp[32] & 0xF;
	offset[HA8_VT][1] = mtp[33] >> 4;
	offset[HA8_VT][2] = mtp[33] & 0xF;
}

/* num / den toward zero, and one more when the remainder is .9995 of den or more (dimming.c: disp_div64_round with
 * two digits; 0 when den is 0, as there) */
static int64_t
ha8_div_round(int64_t num, int64_t den)
{
	bool negative = (num < 0) != (den < 0);
	uint64_t n = num < 0 ? 0 - (uint64_t)num : (uint64_t)num, d = den < 0 ? 0 - (uint64_t)den : (uint64_t)den, q;

	if (d == 0) {
		return 0;
	}
	q = n / d + ((n % d) * 10000 / d + 5) / 10000;
	return negative ? -(int64_t)q : (int64_t)q;
}

/* the voltages a panel makes at the points for register values `reg' with its MTP already added: the centres plus the
 * MTP give the calibrated curve, a CA row plus the MTP what that row shows (dimming.c: mtp_offset_to_vregout). Each
 * point hangs from the next one up, so 255 first. */
static void
ha8_point_volts(const int32_t reg[HA8_TP][3], int64_t volt[HA8_TP][3])
{
	for (int c = 0; c < 3; c++) {
		int32_t step = reg[HA8_VT][c] < 0 ? 0 : reg[HA8_VT][c] > 15 ? 15 : reg[HA8_VT][c];

		volt[HA8_VT][c] = HA8_VREGOUT - HA8_VREGOUT * ha8_vt_table[step] / ha8_points[HA8_VT].denominator;
		for (int p = HA8_V255; p > HA8_VT; p--) {
			const struct ha8_point *t = &ha8_points[p];
			int64_t top = t->from_vt ? volt[HA8_VT][c] : HA8_VREGOUT;
			int64_t span = p == HA8_V255 ? top : top - volt[p + 1][c];

			volt[p][c] = top - span * (t->numerator + reg[p][c]) / t->denominator;
		}
	}
}

/* step 1: the calibrated curve from the MTP, at the points and then at every gray between them (process_dimming's
 * first half: mtp_offset_to_vregout, generate_gray_scale) */
static void
ha8_calibrate(struct ha8_work *w, const uint8_t mtp[HA8_CA])
{
	int32_t reg[HA8_TP][3];

	ha8_mtp(mtp, w->offset);
	for (int p = 0; p < HA8_TP; p++) {
		for (int c = 0; c < 3; c++) {
			reg[p][c] = ha8_points[p].center + w->offset[p][c];
		}
	}
	ha8_point_volts(reg, w->point);
	for (int c = 0; c < 3; c++) {
		w->gray[0][c] = HA8_VREGOUT;
		for (int p = 1; p < HA8_TP; p++) {
			w->gray[ha8_points[p].gray][c] = w->point[p][c];
		}
	}
	for (int p = 0; p + 1 < HA8_TP; p++) {
		int low = ha8_points[p].gray, high = ha8_points[p + 1].gray;

		for (int g = low + 1; g < high; g++) {
			for (int c = 0; c < 3; c++) {
				/* (dimming.c: interpolation) */
				int64_t rise = w->gray[high][c] - w->gray[low][c];

				w->gray[g][c] = w->gray[low][c] + rise * (g - low) / (high - low);
			}
		}
	}
}

/* a gray's luminance on the calibrated curve, 400 * (gray / 255)^2.2, << 24 (generate_gray_scale's gamma_value) */
static uint64_t
ha8_gray_nits(int g)
{
	return (uint64_t)HA8_TARGET * ha8_curve_220[g];
}

/* the gray of the calibrated curve whose luminance is nearest to `nits' (<< 24); the lower on a tie (dimming.c:
 * find_gray_scale_gamma_value) */
static int
ha8_nearest_gray(uint64_t nits)
{
	int g = 0;

	while (g < 255 && ha8_gray_nits(g) < nits) {
		g++;
	}
	if (g > 0 && ha8_gray_nits(g) >= nits && nits - ha8_gray_nits(g - 1) <= ha8_gray_nits(g) - nits) {
		g--;
	}
	return g;
}

/* the gray whose voltage a point of a row takes (step 2; generate_gamma_table's M_GRAY): gray 0 and 1 are their own,
 * the others the nearest gray to the point's luminance on the row's curve, moved by the row's offset. It does not
 * depend on the MTP. (Below 0 it would be 255 in the BSP, whose gray is unsigned: no row comes near; the test
 * checks.) */
static int
ha8_point_gray(const struct ha8_row *row, int p)
{
	const uint32_t *curve = row->curve == HA8_G220 ? ha8_curve_220 : ha8_curve_215;
	uint64_t base = (uint64_t)row->base << HA8_SHIFT;
	int gray = ha8_points[p].gray;

	if (gray <= 1) {
		return gray;
	}
	gray = ha8_nearest_gray(p == HA8_V255 ? base : base * curve[gray] >> HA8_SHIFT) + row->gray[p];
	return gray < 0 ? 0 : gray > 255 ? 255 : gray;
}

/* steps 2 to 4 for one row: its CA (generate_gamma_table, mtp_vregout_to_offset; s6e3ha8.c: copy_tpout_center) */
static void
ha8_row_ca(struct ha8_work *w, const struct ha8_row *row, uint8_t ca[HA8_CA])
{
	int64_t volt[HA8_TP][3];
	int32_t value[HA8_TP][3];

	for (int p = 0; p < HA8_TP; p++) {
		int gray = ha8_point_gray(row, p);

		for (int c = 0; c < 3; c++) {
			volt[p][c] = p == HA8_VT ? w->point[HA8_VT][c] : w->gray[gray][c];
		}
	}
	for (int c = 0; c < 3; c++) {
		value[HA8_VT][c] = ha8_points[HA8_VT].center;  /* (VT is not worked out: the panel's MTP sets it) */
	}
	for (int p = HA8_VT + 1; p < HA8_TP; p++) {
		const struct ha8_point *t = &ha8_points[p];

		for (int c = 0; c < 3; c++) {
			int64_t top = t->from_vt ? volt[HA8_VT][c] : HA8_VREGOUT;
			int64_t span = p == HA8_V255 ? top : top - volt[p + 1][c];
			int64_t most = p == HA8_V255 ? 511 : 255, part, v;

			/* the divider's part at this voltage, less its numerator and the MTP: the register value */
			part = (top - volt[p][c]) * t->denominator - span * t->numerator - span * w->offset[p][c];
			v = ha8_div_round(part, span) + row->color[p][c];
			if (v < 0 || v > most) {
				w->clamped++;
				v = v < 0 ? 0 : most;
			}
			value[p][c] = (int32_t)v;
		}
	}
	for (int i = 0; i < HA8_CA; i++) {
		ca[i] = 0;
	}
	for (int c = 0; c < 3; c++) {
		ca[0] |= (uint8_t)(((value[HA8_V255][c] >> 8) & 1) << c);
		ca[1 + c] = (uint8_t)value[HA8_V255][c];
		for (int p = HA8_V255 - 1; p > HA8_VT; p--) {
			ca[(HA8_V255 - p) * 3 + 1 + c] = (uint8_t)value[p][c];
		}
	}
	ca[32] = (uint8_t)(value[HA8_VT][0] & 0xF);
	ca[33] = (uint8_t)((value[HA8_VT][1] & 0xF) << 4 | (value[HA8_VT][2] & 0xF));
}

/* every row's CA for a panel and its MTP; how many values were kept within range */
static uint32_t
ha8_gamma(struct ha8_work *w, const struct ha8_panel *panel, const uint8_t mtp[HA8_CA], uint8_t ca[HA8_ROWS][HA8_CA])
{
	ha8_calibrate(w, mtp);
	w->clamped = 0;
	for (int r = 0; r < HA8_ROWS; r++) {
		ha8_row_ca(w, &panel->rows[r], ca[r]);
	}
	return w->clamped;
}

