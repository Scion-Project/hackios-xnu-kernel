#!/usr/bin/env python3
"""Generate patches/xnu-8796/: an applied kernel tree as an ordered patch series on pristine XNU.

usage: tools/mk-series.py TREE [OUT]     (TREE: what xnu/apply.sh made; OUT: patches/xnu-8796)

Changes to Apple's files and the files added to the tree go into one patch per directory, in `series`. The drivers stay in
drivers/; what the numbered patches change in them today goes into 9000-driver-fixups.patch, to be folded into the drivers.
Left out, as apply-series.sh makes them another way: HFS (xnu/hfs/hfs.sh), a layer's headers (external-files), the build's choice.
"""
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
BASE = subprocess.check_output([sys.executable, os.path.join(HERE, "os-profile.py"), "get", "xnu_commit"], text=True).strip()
MADE = {"config/MASTER.hakios", "bsd/dev/hakios.drivers.h"}


def git(tree, *args):
    return subprocess.check_output(["git", "-C", tree, *args])


def main():
    tree = os.path.abspath(sys.argv[1])
    out = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(ROOT, "patches", "xnu-8796")
    os.makedirs(out, exist_ok=True)
    drivers = {}
    for line in open(os.path.join(ROOT, "drivers", "map"), encoding="utf-8"):
        words = line.split("#", 1)[0].split()
        if len(words) == 2:
            drivers[words[1]] = os.path.join(ROOT, "drivers", words[0], os.path.basename(words[1]))
    external = {line.split("\t")[1] for line in subprocess.check_output(
        [sys.executable, os.path.join(HERE, "hakios-config.py"), "external-files"], text=True).splitlines()}
    hfs = set()
    for name, top in (("core.list", "bsd/hfs/"), ("encodings.list", "bsd/hfs_encodings/")):
        hfs |= {top + line.strip() for line in open(os.path.join(ROOT, "xnu", "hfs", name), encoding="utf-8") if line.strip()}
    git(tree, "add", "-A", "-N", ".")
    changed = git(tree, "diff", "--no-renames", "--name-only", BASE).decode().split()
    groups = {}
    for path in changed:
        if path in MADE or path in drivers or path in external or path in hfs or path.startswith("BUILD/"):
            continue
        parts = path.split("/")
        groups.setdefault("-".join(parts[:2]) if len(parts) > 2 else parts[0], []).append(path)
    series = []
    for number, name in enumerate(sorted(groups), 1):
        patch = "%04d-%s.patch" % (number * 10, name.replace(".", "_"))
        with open(os.path.join(out, patch), "wb") as f:
            f.write(git(tree, "diff", "--no-renames", "--no-color", "--binary", "--full-index", BASE, "--", *groups[name]))
        series.append(patch)
    with open(os.path.join(out, "series"), "w", encoding="utf-8") as f:
        f.write("# Generated by tools/mk-series.py. Applied in order on pristine XNU, by xnu/apply-series.sh.\n")
        f.write("\n".join(series) + "\n")
    fixups = b""
    for path, source in sorted(drivers.items()):
        result = subprocess.run(["diff", "-u", "--label", "a/" + path, "--label", "b/" + path, source, os.path.join(tree, path)], capture_output=True)
        if result.returncode == 1:
            fixups += b"diff --git a/%s b/%s\n" % (path.encode(), path.encode()) + result.stdout
    with open(os.path.join(out, "9000-driver-fixups.patch"), "wb") as f:
        f.write(fixups)
    print("mk-series: %d patches, %d files; driver fixups %d bytes" % (len(series), sum(map(len, groups.values())), len(fixups)))


if __name__ == "__main__":
    main()
