#!/usr/bin/env python3
"""The core Vulkan commands (every VK_VERSION_1_x) as exported functions of libhakios.vk.dylib.

Mesa's drivers are ICDs: they export vk_icdGetInstanceProcAddr and a loader finds the rest. iOS
has no Vulkan loader, so the library is linked to directly (as MoltenVK is) and has to export
vkCreateInstance and the others itself. Each one goes where Mesa's runtime would send it:
  - the global commands (no dispatchable object) through vk_icdGetInstanceProcAddr(NULL, ...)
  - VkInstance commands through the instance's dispatch table
  - VkPhysicalDevice, VkDevice, VkQueue and VkCommandBuffer commands through Mesa's trampolines,
    which dispatch on the object (vk_physical_device_trampolines, vk_device_trampolines)
Extensions are reached with vkGetInstanceProcAddr / vkGetDeviceProcAddr, as anywhere else.

  mkvkexports.py --xml vk.xml --mesa-util <mesa>/src/vulkan/util --out scion_vk_exports.c
"""
import argparse
import sys

GLOBAL = ('CreateInstance', 'EnumerateInstanceExtensionProperties', 'EnumerateInstanceLayerProperties',
          'EnumerateInstanceVersion')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--xml', required=True)
    ap.add_argument('--mesa-util', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    sys.path.insert(0, a.mesa_util)
    from vk_entrypoints import get_entrypoints_from_xml

    out = ['/* Generated by tools/gfxstream/vk/scion/mkvkexports.py from vk.xml; do not edit. */',
           '#include "vk_dispatch_trampolines.h"',
           '#include "vk_instance.h"',
           '',
           '#define SCION_VK_EXPORT __attribute__((visibility("default")))',
           '',
           'VKAPI_ATTR PFN_vkVoidFunction VKAPI_CALL vk_icdGetInstanceProcAddr(VkInstance, const char *);',
           '']
    n = 0
    for e in get_entrypoints_from_xml([a.xml], False):
        if e.alias or e.guard is not None or e.core_version is None:
            continue
        ret = '' if e.return_type == 'void' else 'return '
        head = 'SCION_VK_EXPORT VKAPI_ATTR %s VKAPI_CALL\nvk%s(%s)\n{' % (e.return_type, e.name, e.decl_params())
        if e.name == 'GetInstanceProcAddr':
            body = '\treturn vk_icdGetInstanceProcAddr(%s);' % e.call_params()
        elif e.name in GLOBAL:
            body = ('\tstatic PFN_vk%s f;\n'
                    '\tif (f == NULL) {\n'
                    '\t\tf = (PFN_vk%s)vk_icdGetInstanceProcAddr(NULL, "vk%s");\n'
                    '\t}\n'
                    '\t%sf(%s);') % (e.name, e.name, e.name, ret, e.call_params())
        elif e.params[0].type == 'VkInstance':
            body = ('\tVK_FROM_HANDLE(vk_instance, scion_instance, %s);\n'
                    '\t%sscion_instance->dispatch_table.%s(%s);') % (e.params[0].name, ret, e.name, e.call_params())
        elif e.is_physical_device_entrypoint():
            body = '\t%svk_physical_device_trampolines.%s(%s);' % (ret, e.name, e.call_params())
        elif e.is_device_entrypoint():
            body = '\t%svk_device_trampolines.%s(%s);' % (ret, e.name, e.call_params())
        else:
            raise SystemExit('mkvkexports.py: vk%s dispatches on nothing known' % e.name)
        out += [head, body, '}', '']
        n += 1
    out.append('/* %d commands */' % n)
    with open(a.out, 'w') as f:
        f.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
